        let currentLang = 'fr';
        let currentTheme = 'dark';

        document.getElementById('langBtn').addEventListener('click', () => {
            currentLang = currentLang === 'fr' ? 'en' : 'fr';
            updateLanguage();
        });

        function updateLanguage() {
            const t = translations[currentLang];
            Object.keys(t).forEach(key => {
                const el = document.getElementById(key);
                if (el) {
                    if (key === 'heroName') {
                        el.innerHTML = t[key].replace('\n', '<br>');
                    } else {
                        el.textContent = t[key];
                    }
                }
            });
        }

        document.getElementById('themeBtn').addEventListener('click', () => {
            currentTheme = currentTheme === 'dark' ? 'light' : 'dark';
            updateTheme();
        });

        function updateTheme() {
            if (currentTheme === 'light') {
                document.body.setAttribute('data-theme', 'light');
                document.getElementById('themeBtn').innerHTML = '<i class="fas fa-sun"></i>';
            } else {
                document.body.removeAttribute('data-theme');
                document.getElementById('themeBtn').innerHTML = '<i class="fas fa-moon"></i>';
            }
        }

        window.addEventListener('scroll', () => {
            const h = document.documentElement;
            const b = document.body;
            const st = 'scrollTop';
            const sh = 'scrollHeight';
            const progress = (h[st] || b[st]) / ((h[sh] || b[sh]) - h.clientHeight) * 100;
            document.getElementById('progressBar').style.width = progress + '%';
        });

        window.addEventListener('scroll', () => {
            const header = document.getElementById('header');
            if (window.scrollY > 50) {
                header.classList.add('scrolled');
            } else {
                header.classList.remove('scrolled');
            }
        });

        const observerOptions = {
            threshold: 0.1,
            rootMargin: '0px 0px -100px 0px'
        };

        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('visible');
                }
            });
        }, observerOptions);

        document.querySelectorAll('.fade-in').forEach(el => observer.observe(el));

        document.getElementById('contactForm').addEventListener('submit', (e) => {
            e.preventDefault();
            alert(currentLang === 'fr' ? 'Merci pour votre message ! Je vous répondrai bientôt.' : 'Thank you for your message! I will reply soon.');
            e.target.reset();
        });

        document.querySelectorAll('a[href^="#"]').forEach(anchor => {
            anchor.addEventListener('click', function(e) {
                e.preventDefault();
                const target = document.querySelector(this.getAttribute('href'));
                if (target) {
                    target.scrollIntoView({ behavior: 'smooth', block: 'start' });
                }
            });
        });